# -*- coding: utf-8 -*-
r"""INSTAGRAM CURADORIA — a revisao dos takes de um Reel pronto: o defeito apontado a mao, o corretor e o registro.

    python motor/instagram_curadoria.py --autoteste

    ETIQUETAS                                   os defeitos de um clique (o texto livre vem junto)
    pedido_correcao(...)  /  ler_correcao(txt)  o Claude reescreve UM take para tirar o defeito apontado
    registrar(base, evento)  /  ocorrencias(base)
        a migalha do erro: cada defeito, a correcao feita, as versoes geradas e a escolhida, em
        data/instagram/aprendizado/ocorrencias.jsonl (so' acrescenta; nunca reescreve)

⭐ A ocorrencia guarda TUDO o que levou ao defeito (fala, quadro, movimento, o prompt mandado ao Veo, o que o whisper
   ouviu) e o que resolveu (a versao escolhida). E' a materia-prima das licoes da fase 2: sem isso, nao ha' o que
   aprender.
"""
import json, os, re, secrets, sys, threading, time

AQUI = os.path.dirname(os.path.abspath(__file__))
if AQUI not in sys.path: sys.path.insert(0, AQUI)
import instagram_roteiro as _rot                                            # noqa: E402

# (id, rotulo) — o id vai para a ocorrencia (a fase 2 conta defeito por etiqueta); o rotulo e' o do botao
ETIQUETAS = [
    ("fala", "Fala errada"), ("pronuncia", "Pronúncia"), ("acao", "Ação não aconteceu"),
    ("maos", "Mãos ou objeto deformado"), ("rosto", "Rosto mudou"), ("texto", "Legenda ou texto na tela"),
    ("camera", "Câmera mexeu"), ("morph", "Morph ou corte estranho"), ("quadro", "Quadro de abertura ruim"),
    ("tempo", "Fala longa ou cortada"),
]
IDS_ETIQUETA = {e for e, _ in ETIQUETAS}
_trava = threading.Lock()


def _arq(base):
    return os.path.join(base, "aprendizado", "ocorrencias.jsonl")


def nova_id():
    return f"{time.strftime('%Y%m%d-%H%M%S')}-{secrets.token_hex(2)}"


def registrar(base, evento):
    """Acrescenta um evento (dict com "tipo") ao registro das ocorrencias. Devolve o evento gravado."""
    ev = {"t": round(time.time(), 2), **evento}
    os.makedirs(os.path.dirname(_arq(base)), exist_ok=True)
    with _trava, open(_arq(base), "a", encoding="utf-8") as f:
        f.write(json.dumps(ev, ensure_ascii=False) + "\n")
    return ev


def ocorrencias(base):
    """Os eventos gravados, na ordem. Linha quebrada (queda no meio da escrita) e' pulada, nunca derruba a leitura."""
    try:
        linhas = open(_arq(base), encoding="utf-8").read().splitlines()
    except OSError:
        return []
    saida = []
    for l in linhas:
        try:
            saida.append(json.loads(l))
        except ValueError:
            continue
    return saida


def pedido_correcao(avatar, idioma, cta, take, defeito, etiquetas, ouvido, prompt, edicao=None, extras=""):
    """O pedido ao Claude para refazer UM take. `take` = {"fala", "quadro", "movimento", "cta"}.
    `edicao` = {"fala"?, "movimento"?} escritos a mao no editor: entram como a intencao de quem revisa, nunca como
    texto final. ⛔ (18/10) o campo "movimento" recebia a descricao do ERRO em portugues ("ela esta' com tres
    maos"): mandado direto, isso virava o prompt do Veo. `extras` = as licoes ativas (as mesmas do roteiro)."""
    rotulos = dict(ETIQUETAS)
    marcas = ", ".join(rotulos[e] for e in etiquetas if e in rotulos) or "nenhuma"
    regra_cta = f"\nThis take is the call to action. {_rot.regra_cta(cta, avatar)}" if take.get("cta") else ""
    mao = "".join(f'\n- the reviewer also rewrote the {k} by hand: "{v}"' for k, v in (edicao or {}).items() if v)
    if mao: mao += ("\n  (treat these as the reviewer's intent: it may be a note in Portuguese about the defect, not "
                    "text to copy; the final fields must follow the rules below)")
    return f"""You fix ONE take of a short vertical video (Instagram Reel). The take is generated by Google Veo from a
still frame: the same frame opens and closes the 8-second shot, and the presenter speaks one line in it.
Return ONLY JSON.

The presenter: {avatar.get("quem") or avatar.get("descricao", "")}
Target language: {_rot.IDIOMAS[idioma]["lingua"]}.

The take as it was generated:
- fala (the line the presenter had to say): {take.get("fala", "")}
- what a speech recognizer heard in the generated video: {ouvido or "(not measured)"}
- quadro (items in front of the presenter in the opening frame): {take.get("quadro", "")}
- movimento: {take.get("movimento", "")}
- the full prompt sent to Veo: {prompt}

The reviewer watched it and reported (in Portuguese) — tags: {marcas}; note: "{defeito.strip()}"{mao}

Rewrite the take to remove the reported defect with the smallest change that can work, keeping the meaning of
the line and its place in the video. Typical fixes: a word the voice mispronounces becomes a common synonym; an
action that did not happen or deformed the hands becomes a simpler, slower gesture with fewer items; a line that
was cut or repeated becomes shorter.
{_rot.regras_take(idioma, extras, avatar)}{regra_cta}
Set "refazer_quadro" to true ONLY when the defect is in the opening or the end frame itself (wrong or missing
items, an item that should not be there, or an action that did not complete because the end frame does not show
its result); then "quadro" and "quadro_fim" name the corrected items. Otherwise keep them as they are.

{_rot.REGRAS_CONTEUDO}

JSON format:
{{"fala": "...", "quadro": "...", "quadro_fim": "...", "movimento": "...", "refazer_quadro": false,
  "motivo": "one short sentence in Brazilian Portuguese saying what you changed and why"}}"""


def ler_correcao(texto):
    """A resposta do corretor -> {"fala", "quadro", "movimento", "refazer_quadro", "motivo"} ou None (fora do formato)."""
    m = re.search(r"\{.*\}", texto or "", flags=re.S)
    if not m: return None
    try:
        d = json.loads(m.group(0))
    except ValueError:
        return None
    if not isinstance(d, dict): return None
    campos = {}
    for k in ("fala", "movimento"):
        v = d.get(k)
        if not isinstance(v, str) or not v.strip(): return None
        campos[k] = v.strip()
    campos["fala"] = re.sub(r"\s*[—–]\s*|\s+-\s+", ", ", campos["fala"])          # ⛔ o Veo vocaliza o travessao
    campos["quadro"] = d["quadro"].strip() if isinstance(d.get("quadro"), str) else ""
    campos["quadro_fim"] = d["quadro_fim"].strip() if isinstance(d.get("quadro_fim"), str) else ""
    campos["refazer_quadro"] = d.get("refazer_quadro") is True and bool(campos["quadro"])
    campos["motivo"] = str(d.get("motivo") or "").strip()
    return campos


def _autoteste():
    import tempfile
    ok = True

    def caso(nome, cond):
        nonlocal ok; print(("  OK  " if cond else "  ERRO"), nome); ok &= bool(cond)

    base = tempfile.mkdtemp(prefix="min-ig-cur-")
    caso("sem registro: lista vazia", ocorrencias(base) == [])
    e = registrar(base, {"tipo": "defeito", "id": "x", "defeito": "falou forinho"})
    registrar(base, {"tipo": "escolha", "id": "x", "v": 3})
    open(_arq(base), "a", encoding="utf-8").write('{"quebrada": \n')
    ev = ocorrencias(base)
    caso("⭐ registro so' acrescenta, na ordem, com a hora", [x["tipo"] for x in ev] == ["defeito", "escolha"] and e["t"] > 0)
    caso("⛔ linha quebrada nao derruba a leitura", len(ev) == 2)
    caso("ids unicos", nova_id() != nova_id())

    take = {"fala": "Sai um pão macio, fofinho, sem glúten.", "quadro": "A sliced loaf on a board.",
            "movimento": "As she speaks, both hands lift the loaf. After the line, she sets it back.", "cta": False}
    p = pedido_correcao(_rot.TOMIKO, "pt", {"tipo": "palavra", "palavra": "eu quero"}, take,
                        "falou forinho", ["pronuncia", "inexistente"], "Sai um pão macio, forinho", "PROMPT")
    caso("pedido: o take, o que foi ouvido, o prompt e o defeito", "fofinho" in p and "forinho" in p and "PROMPT" in p
         and '"falou forinho"' in p and "Pronúncia" in p)
    caso("⭐ pedido: as mesmas regras de take do roteiro", _rot.regras_take("pt") in p and "Brazilian Portuguese" in p)
    caso("pedido: take comum nao leva a regra do CTA", '"eu quero,"' not in p and "by hand" not in p)
    pm = pedido_correcao(_rot.TOMIKO, "pt", {}, take, "x", [], "", "P", {"movimento": "ela esta com tres maos"})
    caso("⭐ pedido: a edicao a mao entra como intencao, nao como texto final",
         'rewrote the movimento by hand: "ela esta com tres maos"' in pm and "not text to copy" in pm)
    pc = pedido_correcao(_rot.TOMIKO, "pt", {"tipo": "palavra", "palavra": "eu quero"}, {**take, "cta": True}, "x", [], "", "P")
    caso("pedido: o take do CTA leva a regra do CTA", '"eu quero,"' in pc)
    caso("⭐ pedido: as licoes ativas entram nas regras", "- LICAO Y" in pedido_correcao(_rot.TOMIKO, "pt", {}, take, "x", [], "",
                                                                                     "P", extras="- LICAO Y"))
    r = ler_correcao('ok {"fala": "Sai um pão macio — leve", "quadro": "Q", "movimento": "M", "refazer_quadro": true,'
                     ' "motivo": "troquei fofinho"}')
    caso("ler: campos e travessao trocado", r and r["fala"] == "Sai um pão macio, leve" and r["refazer_quadro"] and r["motivo"])
    caso("⛔ ler: refazer quadro sem quadro = nao refaz",
         ler_correcao('{"fala": "a", "movimento": "b", "refazer_quadro": true}')["refazer_quadro"] is False)
    caso("⛔ ler: sem fala = None", ler_correcao('{"fala": "", "movimento": "b"}') is None)
    caso("⛔ ler: lixo = None", ler_correcao("sem json") is None and ler_correcao("[1, 2]") is None)
    print("\nautoteste:", "PASSOU" if ok else "FALHOU")
    return ok


if __name__ == "__main__":
    if hasattr(sys.stdout, "reconfigure"): sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    sys.exit(0 if _autoteste() else 1)
